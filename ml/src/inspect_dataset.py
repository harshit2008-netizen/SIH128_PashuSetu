"""Inspect the downloaded LSD dataset before training (spec 11.2 step 3).

Run from ml/:  uv run python src/inspect_dataset.py
Writes reports/dataset_inspection.md: class folders and counts, image sizes per
source folder, broken files, near-duplicates, and the split that train.py will make.
It reuses train.py's folder mapping and duplicate logic so the two cannot disagree.
"""

import sys
from collections import Counter
from pathlib import Path

import numpy as np

ML = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ML / "kaggle" / "lsd_image_classifier"))
import train  # noqa: E402  (plain functions; TensorFlow is only imported when training)

DATA = ML / "data" / "raw" / "lsd"
REPORT = ML / "reports" / "dataset_inspection.md"


def size_summary(items) -> str:
    widths = np.array([i["size"][0] for i in items])
    heights = np.array([i["size"][1] for i in items])
    common = Counter(i["size"] for i in items).most_common(1)[0]
    return (f"{np.median(widths):.0f}x{np.median(heights):.0f} median, "
            f"{widths.min()}-{widths.max()} wide, most common {common[0][0]}x{common[0][1]} ({common[1]})")


def main() -> None:
    items, notes = train.find_images(DATA)
    ok, broken = train.hash_images(items)
    by_source = {}
    for item in ok:
        by_source.setdefault(item["source"], []).append(item)
    raw_counts = Counter(i["label"] for i in ok)
    kept, dedupe = train.dedupe_and_group([dict(i) for i in ok])
    train.split_groups(kept)
    split_counts = {s: Counter(i["label"] for i in kept if i["split"] == s) for s in ("train", "val", "test")}

    dropped_by_name = [n for n in notes if n.startswith("dropped")]
    lines = [
        "# LSD dataset inspection",
        "",
        "Dataset: CowHealth-6K (`drtawfikrrahman/cowhealth-6k-cow-disease-detection`), CC0-1.0.",
        "Generated by `ml/src/inspect_dataset.py` with the same rules `train.py` uses on Kaggle.",
        "",
        "## Folders",
        "",
        "| Folder | Label | Images read | Size |",
        "|---|---|---|---|",
        *[f"| {s} | {v[0]['label']} | {len(v)} | {size_summary(v)} |" for s, v in sorted(by_source.items())],
        "",
        *[f"- {n}" for n in notes if n.startswith("ignored")],
        f"- {len(dropped_by_name)} files dropped because the file name names another disease"
        + (f", e.g. `{dropped_by_name[0].split(chr(39))[1]}`" if dropped_by_name else ""),
        f"- {len(broken)} broken files" + "".join(f"\n  - `{b['path'].name}`: {b['error']}" for b in broken[:10]),
        "",
        "## Duplicates and split",
        "",
        f"- Before dedupe: {dict(raw_counts)}",
        f"- Near-duplicates (hash distance <= {train.DUPLICATE_DISTANCE}) removed: {dedupe['duplicates_removed']}",
        f"- Images dropped because copies of the same photo had both labels: {dedupe['conflicting_label_images_dropped']}",
        f"- Similar-photo groups (distance <= {train.GROUP_DISTANCE}) kept inside one split: {dedupe['groups']} groups",
        "",
        "| Split | healthy | lsd |",
        "|---|---|---|",
        *[f"| {s} | {c['healthy']} | {c['lsd']} |" for s, c in split_counts.items()],
        "",
        "## Risks to report",
        "",
        "- Each label comes from different source folders (see sizes above). If the sources differ in framing,",
        "  background or resolution, the model can learn the source instead of the lumps. This is listed in the model card.",
        "- Photos are from the internet and public repositories, not from field use in Maharashtra.",
    ]
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
